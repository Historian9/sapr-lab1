// Блок 1: 4-разрядный счётчик Джонсона (ЛР1, вариант 3)
// Последовательность состояний Q[3:0]:
//   0000 -> 0001 -> 0011 -> 0111 -> 1111 -> 1110 -> 1100 -> 1000 -> 0000 ...
// Сдвиг влево, в младший разряд записывается инверсия старшего.
// Недопустимые состояния (не входящие в цикл) сбрасываются в 0000.
module johnson4
(
	C, Q
);
input C;            // синхросигнал (кнопка KEY[3])
output [3:0] Q;     // состояние счётчика
reg [3:0] Q;

initial Q = 4'b0000; // начальное состояние после загрузки ПЛИС

always @(posedge C)
begin
	case (Q)
		4'b0000, 4'b0001, 4'b0011, 4'b0111,
		4'b1111, 4'b1110, 4'b1100, 4'b1000:
			Q <= {Q[2:0], ~Q[3]};
		default:
			Q <= 4'b0000;           // самокоррекция
	endcase
end
endmodule
